    def logprob(self, X):
        """
        Computes the log-probability of data sequence X given the HMM.
        """
        # get emission probabilities for each state over time
        pX = np.array([self.outputDistr[j].prob(X) for j in range(self.nStates)])
        
        # forward algorithm to get scaling factors
        _, c = self.stateGen.forward(pX)
        
        # Log-likelihood is the negative sum of the log scaling factors
        return -np.sum(np.log(c))


    def adaptStart(self):
        """Initializes the accumulators fora new EM training loop."""
        self.stateGen.adaptStart()
        for dist in self.outputDistr:
            dist.adaptStart()

    def adaptSet(self):
        """The M-step: Updates the parameters using the accumulated statistics."""
        self.stateGen.adaptSet()
        for dist in self.outputDistr:
            dist.adaptSet()

    def adaptAccum(self, X):
        """
        The E-step: Computes posteriors (gamma and xi) and accumulates statistics.
        """
        T = X.shape[1]
        pX = np.array([dist.prob(X) for dist in self.outputDistr])
        
        # Run Forward and Backward
        alpha_hat, c = self.stateGen.forward(pX)
        beta_hat = self.stateGen.backward(c, pX)
        
        # Compute Gamma (probability of being in state i at time t) and normalize
        gamma = (alpha_hat * beta_hat) / c.reshape(1, -1)
        gamma = gamma / np.sum(gamma, axis=0)
        
        # Compute Xi (probability of transitioning from state i to j at time t)
        xi = np.zeros((self.nStates, self.nStates, T - 1))
        for t in range(T - 1):
            for i in range(self.nStates):
                for j in range(self.nStates):
                    xi[i, j, t] = alpha_hat[i, t] * self.stateGen.A[i, j] * pX[j, t + 1] * beta_hat[j, t + 1]
            
            # Normalize
            xi[:, :, t] = xi[:, :, t] / np.sum(xi[:, :, t])
            

        # Pass posteriors to accumulate
        self.stateGen.adaptAccum(gamma, xi)
        for state_idx, dist in enumerate(self.outputDistr):
            # Pass the observation data and the weight for a specific state
            dist.adaptAccum(X, gamma[state_idx, :])